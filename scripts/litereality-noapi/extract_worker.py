"""Offline compatibility smoke test of the pinned upstream extraction function.

This is not the full public ingest stage or a reconstruction result.
"""
import argparse
import faulthandler
import json
import os
from pathlib import Path
import pickle
import socket
import zipfile
from common import frame_files,save,digest


def deny_network(*args,**kwargs):raise RuntimeError('Network disabled in offline extraction smoke test')


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--scan',type=Path,required=True)
    ap.add_argument('--report',type=Path,required=True)
    ap.add_argument('--scene-name',default='studio_2573')
    args=ap.parse_args();scan=args.scan.resolve();report=args.report.resolve()
    inputs=frame_files(scan)
    faulthandler.dump_traceback_later(180,repeat=False)
    print('Loading official extraction dependencies (network disabled).',flush=True)
    socket.socket.connect=deny_network;socket.socket.connect_ex=deny_network;socket.create_connection=deny_network
    # The upstream USD parser extracts nested ZIP members: validate these before calling it.
    usdz=scan/'roomplan/room.usdz'
    if not usdz.is_file():usdz=scan/'room.usdz'
    with zipfile.ZipFile(usdz) as archive:
        for m in archive.infolist():
            p=Path(m.filename)
            if p.is_absolute() or '..' in p.parts or '\\' in m.filename:raise ValueError('Unsafe USDZ member')
        if archive.testzip() is not None:raise ValueError('Invalid USDZ CRC')
    os.environ['LITEREALITY_OUTPUT']=str(report/'offline_extraction')
    os.environ['LITEREALITY_FINAL']=str(report/'offline_extraction')
    from litereality_agent.pipeline.scene_init import paths
    from litereality_agent.pipeline.scene_init.ingest.extract.extract_scene import extract
    faulthandler.cancel_dump_traceback_later()
    print('Parsing the original capture with the pinned upstream extractor.',flush=True)
    paths.enter_work_root(args.scene_name)
    scene=extract(str(scan),args.scene_name)
    import numpy as np
    from PIL import Image,ImageOps,ImageDraw
    # Only read pickles freshly generated by the inspected upstream parser, never input pickles.
    parsed={}
    for name in ('walls','objects','floor','wall_holes'):
        with (scene/(name+'.pkl')).open('rb') as f:parsed[name]=pickle.load(f)
    rgbd=paths.work_root()/'input/rgbd'/args.scene_name
    counts={name:len(list((rgbd/name).iterdir())) for name in ('image','depth','intrinsic','extrinsic')}
    if any(n!=len(inputs) for n in counts.values()):raise ValueError('Official extractor did not preserve every input frame')
    max_k_error,max_pose_error=0.,0.
    rows=[];rgb_sizes=set();depth_sizes=set()
    selected=set(np.linspace(0,len(inputs)-1,min(12,len(inputs)),dtype=int).tolist())
    tiles=[]
    for i,meta_path in enumerate(inputs):
        metadata=json.loads(meta_path.read_text())
        number=meta_path.stem.removeprefix('frame_')
        rgb_path=scan/(meta_path.stem+'.jpg')
        depth_path=scan/('depth_'+number+'.png')
        with Image.open(rgb_path) as im:
            width,height=im.size;rgb_sizes.add(im.size)
            im.verify()
        with Image.open(depth_path) as im:input_depth=np.array(im)
        if input_depth.ndim!=2 or input_depth.dtype!=np.uint16:raise ValueError('Expected uint16 depth PNG: '+depth_path.name)
        dh,dw=input_depth.shape;depth_sizes.add((dw,dh))
        reference=np.array(metadata['cameraPoseARFrame']).reshape(4,4)@np.diag([1,-1,-1,1])
        pose=np.load(rgbd/'extrinsic'/f'extrinsic_{i}.npy')
        k=np.array(metadata['intrinsics'],dtype=float).reshape(3,3);k[0]*=dw/width;k[1]*=dh/height
        actual_k=np.load(rgbd/'intrinsic'/f'intrinsic_{i}.npy')
        if not all(np.isfinite(v).all() for v in (reference,pose,k,actual_k)):raise ValueError('Nonfinite camera parameter')
        max_pose_error=max(max_pose_error,float(np.max(abs(pose-reference))))
        max_k_error=max(max_k_error,float(np.max(abs(k-actual_k))))
        # Upstream uses a .jpg suffix but copies PNG bytes; verify content, not suffix.
        output_depth=np.array(Image.open(rgbd/'depth'/f'frame_{i}.jpg'))
        np.testing.assert_array_equal(output_depth,input_depth)
        if digest(rgb_path)!=digest(rgbd/'image'/f'frame_{i}.jpg'):raise ValueError('RGB output differs from input')
        valid=input_depth[input_depth>0]
        row=dict(input_frame=meta_path.stem,output_index=i,rgb_size=[width,height],depth_size=[dw,dh],
            valid_depth_fraction=float(np.mean(input_depth>0)),
            depth_median_m=float(np.median(valid)/1000) if len(valid) else None)
        conf_path=scan/('conf_'+number+'.png')
        if conf_path.is_file():
            with Image.open(conf_path) as im:conf=np.array(im)
            if conf.shape!=input_depth.shape:raise ValueError('Confidence/depth shape mismatch')
            row['high_confidence_fraction']=float(np.mean(conf==2))
            row['confidence_values']=np.unique(conf).tolist()
        rows.append(row)
        if i in selected:
            with Image.open(rgb_path) as im:
                thumb=ImageOps.contain(ImageOps.exif_transpose(im).convert('RGB'),(320,240))
            tile=Image.new('RGB',(340,275),'#202020');tile.paste(thumb,((340-thumb.width)//2,8))
            ImageDraw.Draw(tile).text((10,250),meta_path.stem,fill='white');tiles.append(tile)
    save(report/'frame_audit.json',rows)
    sheet=Image.new('RGB',(340*4,275*((len(tiles)+3)//4)),'#202020')
    for i,tile in enumerate(tiles):sheet.paste(tile,((i%4)*340,(i//4)*275))
    sheet.save(report/'rgb_contact_sheet.jpg',quality=85)
    if max_pose_error>1e-5 or max_k_error>1e-4:raise ValueError('Camera conversion mismatch')
    summary=dict(status='offline_extraction_passed',full_agent_run=False,
        scene_name=args.scene_name,frames=counts,wall_count=len(parsed['walls']),object_count=len(parsed['objects']),
        rgb_sizes=sorted(rgb_sizes),depth_sizes=sorted(depth_sizes),
        average_valid_depth_fraction=float(np.mean([r['valid_depth_fraction'] for r in rows])),
        wall_holes_container_type=type(parsed['wall_holes']).__name__,
        max_pose_conversion_error=max_pose_error,max_intrinsics_conversion_error=max_k_error,
        depth_pixels_exact=True,scene_data=str(scene),
        notes=['Upstream depth files have .jpg suffix but retain lossless PNG bytes.',
               'RGB bytes are preserved; saved intrinsics are checked against actual RGB/depth dimensions.',
               'Depth range uses the official scanner convention of millimetres; not independently calibrated accuracy.',
               'This checks extraction only; no layout agent, image generation, TRELLIS or authoring ran.'])
    (report/'extraction_summary.json').write_text(json.dumps(summary,indent=2)+'\n')
    print(json.dumps(summary,indent=2))


if __name__=='__main__':main()
